"""Build one candidate strategy in two phases: prepare (source transform / `opt` pass pipeline) and compile
(clang or llc+link -> executable)."""
from __future__ import annotations

import shutil
import time
from dataclasses import dataclass, field
from pathlib import Path

from ..compiler import compilation as cc
from ..compiler import passes as reg
from ..compiler.compilation import EXE_SUFFIX
from ..compiler.source_transforms import TRANSFORMS

REMARK_FLAGS = ["-Rpass=loop-vectorize|slp-vectorizer", "-Rpass-missed=loop-vectorize",
                "-Rpass-analysis=loop-vectorize"]


@dataclass
class CandidateBuild:
    strategy: reg.Strategy
    dir: Path
    language: str = "c"
    base_src: Path | None = None
    unopt_ll: Path | None = None
    src: Path | None = None  # source actually compiled
    exe: Path | None = None
    status: str = "pending"  # ok | failed | skipped
    failure: str | None = None
    compile_ms: float | None = None
    opt_ms: float | None = None
    source_path: Path | None = None  # set only when a real source transformation produced new source
    ir_path: Path | None = None
    applied_passes: list[str] = field(default_factory=list)
    pipeline_text: str = ""
    techniques: list[str] = field(default_factory=list)
    remarks: list[dict] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    exe_hash: str | None = None
    command: list[str] = field(default_factory=list)


def prepare_candidate(strategy: reg.Strategy, language: str, base_src: Path, unopt_ll: Path | None, root: Path) -> CandidateBuild:
    """Phase 1: produce the artefact that gets compiled (transformed source or optimised IR)."""
    d = root / "variants" / strategy.id
    d.mkdir(parents=True, exist_ok=True)
    cb = CandidateBuild(strategy=strategy, dir=d, language=language, base_src=base_src, unopt_ll=unopt_ll)
    try:
        if strategy.kind == "ir_pipeline":
            if unopt_ll is None or not unopt_ll.exists():
                cb.status, cb.failure = "skipped", "Unoptimised LLVM IR unavailable"
                return cb
            out_ll = d / "optimized.ll"
            t0 = time.perf_counter()
            r = cc.run_opt(unopt_ll, strategy.pipeline or "", out_ll, remarks=True)
            cb.opt_ms = (time.perf_counter() - t0) * 1000
            cb.command = r.cmd
            if not r.ok:
                cb.status, cb.failure = "failed", "opt failed: " + r.reason()
                return cb
            cb.remarks = cc.parse_remarks(r.stderr)
            v = cc.verify_ir(out_ll)
            if not v.ok:
                cb.status, cb.failure = "failed", "IR verifier rejected output: " + v.reason()
                return cb
            cb.ir_path = out_ll
            cb.pipeline_text = strategy.pipeline or ""
            cb.applied_passes = cc.pipeline_passes(cb.pipeline_text, unopt_ll)
            cb.techniques = reg.techniques_from_passes(cb.pipeline_text)
        else:
            src = d / cc.source_filename(language)
            if strategy.source_transform:
                original = base_src.read_text(encoding="utf-8")
                tr = TRANSFORMS[strategy.source_transform](original, language)
                if tr.changes == 0 or tr.source == original:
                    cb.status, cb.failure = "skipped", "Not applicable: " + (tr.notes[0] if tr.notes else "transform changed nothing")
                    return cb
                src.write_text(tr.source, encoding="utf-8")
                cb.source_path = src
                cb.warnings.extend(tr.notes)
            else:
                shutil.copyfile(base_src, src)
            cb.src = src
            cb.pipeline_text = reg.flags_pipeline(language, strategy.flags)
            cb.applied_passes = cc._split_top_level(cb.pipeline_text)
            cb.techniques = reg.techniques_from_passes(cb.pipeline_text)
        cb.status = "prepared"
    except cc.CompilerError as exc:
        cb.status, cb.failure = "failed", str(exc)
    return cb


def compile_candidate(cb: CandidateBuild) -> CandidateBuild:
    """Phase 2: build the executable and hash it (for duplicate detection)."""
    if cb.status != "prepared":
        return cb
    exe = cb.dir / f"program{EXE_SUFFIX}"
    s = cb.strategy
    try:
        if s.kind == "ir_pipeline":
            link = cc.ir_to_exe(cb.ir_path, exe, cb.language)
            cb.compile_ms = (cb.opt_ms or 0) + link.elapsed_ms
            if not link.ok:
                cb.status, cb.failure = "failed", "llc/link failed: " + link.reason()
                return cb
            cb.warnings.append("Machine code generated by `llc -O2` from the transformed IR (clang front-end not re-run).")
        else:
            t0 = time.perf_counter()
            step = cc.compile_exe(cb.src, cb.language, list(s.flags), exe, extra=REMARK_FLAGS)
            cb.compile_ms = (time.perf_counter() - t0) * 1000
            cb.command = step.cmd
            if not step.ok:
                cb.status, cb.failure = "failed", step.reason()
                return cb
            cb.remarks = cc.parse_remarks(step.stderr)
    except cc.CompilerError as exc:
        cb.status, cb.failure = "failed", str(exc)
        return cb
    if not exe.exists():
        cb.status, cb.failure = "failed", "executable was not produced"
        return cb
    cb.exe, cb.exe_hash, cb.status = exe, cc.sha256_file(exe), "ok"
    return cb
